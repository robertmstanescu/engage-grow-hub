/**
 * Build the SQL that loads the Work portfolio into Supabase as DRAFTS.
 *
 *   bun scripts/work-portfolio/build-sql.ts <out.sql>
 *
 * Lovable runs the file. It is safe to run more than once:
 *   - proof points: the six agreed ones are inserted when no row has the
 *     same label and value; existing rows (and their approval) are left
 *     alone
 *   - work items: inserted as status 'draft'. A slug that already exists
 *     is refreshed only while it is still a draft; a published item is
 *     never touched, so nothing on the live site changes until the owner
 *     publishes each piece in the admin
 *
 * Images are static files in public/work/<slug>/ and serve once the
 * code is deployed.
 */
import fs from "node:fs";
import { WORK_PORTFOLIO } from "../../src/lib/work/entries";
import { PROOF_POINTS, buildCaseRows, coverPath, ogPath, type ProofKey } from "../../src/lib/work/portfolio";

const out = process.argv[2];
if (!out) {
  console.error("usage: bun scripts/work-portfolio/build-sql.ts <out.sql>");
  process.exit(2);
}

/** A SQL string literal (dollar quoting would also work; this keeps it plain). */
const q = (v: string) => `'${String(v).replace(/'/g, "''")}'`;
const arr = (list: readonly string[]) => `ARRAY[${list.map(q).join(", ")}]::text[]`;
const proofId = (k: ProofKey) =>
  `(SELECT id FROM public.proof_points WHERE label = ${q(PROOF_POINTS[k].label)} AND value = ${q(PROOF_POINTS[k].value)} ORDER BY created_at LIMIT 1)`;

/** Which proof point backs an entry's card metric, if any. */
const metricProof = (metric?: string): ProofKey | undefined =>
  (Object.keys(PROOF_POINTS) as ProofKey[]).find((k) => PROOF_POINTS[k].value === metric);

const lines: string[] = [
  "-- Work portfolio, generated by scripts/work-portfolio/build-sql.ts. Do not edit by hand.",
  `-- ${WORK_PORTFOLIO.length} work items as DRAFTS, plus the agreed proof points.`,
  "BEGIN;",
  "",
];

(Object.keys(PROOF_POINTS) as ProofKey[]).forEach((k, i) => {
  const p = PROOF_POINTS[k];
  lines.push(
    `INSERT INTO public.proof_points (label, value, approved, pillars, sort_order, source_note)`,
    `SELECT ${q(p.label)}, ${q(p.value)}, true, ${arr(p.pillars)}, ${(i + 1) * 10}, ${q(p.note)}`,
    `WHERE NOT EXISTS (SELECT 1 FROM public.proof_points WHERE label = ${q(p.label)} AND value = ${q(p.value)});`,
    "",
  );
});

for (const e of WORK_PORTFOLIO) {
  const rows = JSON.stringify(buildCaseRows(e));
  const mp = metricProof(e.metric);
  const cols: [string, string][] = [
    ["slug", q(e.slug)],
    ["type", q(e.type)],
    ["pillar", q(e.pillar)],
    ["title", q(e.title)],
    ["summary", q(e.summary)],
    ["metric", q(e.metric || "")],
    ["metric_label", q(e.metricLabel || "")],
    ["proof_point_id", mp ? proofId(mp) : "NULL"],
    ["card_style", q(e.cardStyle)],
    ["pull_line", q(e.pullLine)],
    ["honesty_label", q(e.honestyLabel)],
    ["role_title", q(e.roleTitle)],
    ["year", q(e.year)],
    ["tags", arr(e.tags)],
    ["cover_image", q(coverPath(e.slug))],
    ["cover_image_alt", q(e.cover.alt)],
    ["link_out", q(e.linkOut || "")],
    ["has_case_study", "true"],
    ["case_rows", `${q(rows)}::jsonb`],
    ["draft_case_rows", `${q(rows)}::jsonb`],
    [
      "case_proof_ids",
      e.proofs.length ? `ARRAY(SELECT id FROM public.proof_points WHERE (label, value) IN (${e.proofs.map((k) => `(${q(PROOF_POINTS[k].label)}, ${q(PROOF_POINTS[k].value)})`).join(", ")}))` : "'{}'::uuid[]",
    ],
    ["featured_home", e.featuredHome ? "true" : "false"],
    ["sort_order", String(e.n * 10)],
    ["status", q("draft")],
    ["meta_title", q(e.metaTitle)],
    ["meta_description", q(e.metaDescription)],
    ["og_image", q(ogPath(e.slug))],
    ["ai_summary", q(e.aiSummary)],
  ];
  const names = cols.map(([c]) => c);
  lines.push(
    `-- ${String(e.n).padStart(2, "0")} ${e.title}`,
    `INSERT INTO public.work_items (${names.join(", ")})`,
    `VALUES (${cols.map(([, v]) => v).join(",\n  ")})`,
    `ON CONFLICT (slug) DO UPDATE SET ${names
      .filter((c) => c !== "slug" && c !== "status")
      .map((c) => `${c} = EXCLUDED.${c}`)
      .join(", ")}, updated_at = now()`,
    `WHERE public.work_items.status = 'draft';`,
    "",
  );
}

lines.push("COMMIT;", "");
fs.writeFileSync(out, lines.join("\n"));
console.log(`wrote ${out}: ${WORK_PORTFOLIO.length} work items`);
