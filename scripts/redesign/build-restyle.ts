/**
 * Build the redesign restyle from a content snapshot.
 *
 *   bun scripts/redesign/build-restyle.ts <snapshotDir> <outDir>
 *
 * <snapshotDir> holds site_content.json and cms_pages.json (optionally
 * blog_posts.json): plain JSON arrays of the table rows, exported from
 * the live database. Nothing here talks to Supabase.
 *
 * Writes to <outDir>:
 *   - the same JSON files with restyled rows (used by the local preview)
 *   - restyle.sql: UPDATE statements for the DRAFT columns only
 *   - text-diff.txt: per page, "same" or the lines that differ
 *   - gap-content.txt: every piece of text ADDED after the restyle
 *     (buttons, the proof strip, repeated blocks), for the owner to read
 *
 * Exits non-zero if any page's visible text changed in the restyle
 * step, so a restyle that touches copy can never produce SQL.
 */
import fs from "node:fs";
import path from "node:path";
import { arrangeHome, restyleRows, kindForSlug, visibleText } from "../../src/lib/redesign/restyle";
import { applyGapContent, type GapNote } from "../../src/lib/redesign/gapContent";

const [snapshotDir, outDir] = process.argv.slice(2);
if (!snapshotDir || !outDir) {
  console.error("usage: bun scripts/redesign/build-restyle.ts <snapshotDir> <outDir>");
  process.exit(2);
}

type Row = Record<string, unknown> & { [key: string]: any }; // eslint-disable-line @typescript-eslint/no-explicit-any

const read = (name: string): Row[] => {
  try {
    return JSON.parse(fs.readFileSync(path.join(snapshotDir, name), "utf8"));
  } catch (error) {
    console.error(`Cannot read ${name} in ${snapshotDir}: ${(error as Error).message}`);
    process.exit(2);
  }
};
fs.mkdirSync(outDir, { recursive: true });

const rowsOf = (content: unknown): Row[] =>
  Array.isArray(content) ? (content as Row[]) : ((content as Row | null)?.rows as Row[]) || [];
const withRows = (content: unknown, rows: Row[]): unknown =>
  Array.isArray(content) ? rows : { ...(content as Row), rows };

/** Dollar-quote a JSON document for SQL with a tag that cannot collide. */
const sqlJson = (value: unknown): string => {
  const json = JSON.stringify(value);
  let tag = "mc";
  while (json.includes(`$${tag}$`)) tag += "x";
  return `$${tag}$${json}$${tag}$::jsonb`;
};

const sql: string[] = [
  "-- Redesign restyle. Writes DRAFT columns only; nothing goes live until Publish.",
  "-- Generated by scripts/redesign/build-restyle.ts. Do not edit by hand.",
  "begin;",
];
const report: string[] = [];
const gapNotes: GapNote[] = [];
let homeRows: Row[] = [];
let failed = false;

const check = (label: string, before: Row[], after: Row[]) => {
  const a = visibleText(before).split("\n").sort();
  const b = visibleText(after).split("\n").sort();
  const missing = a.filter((line) => !b.includes(line));
  const added = b.filter((line) => !a.includes(line));
  if (!missing.length && !added.length) {
    report.push(`${label}: same`);
    return;
  }
  failed = true;
  report.push(`${label}: CHANGED`, ...missing.map((l) => `  - ${l}`), ...added.map((l) => `  + ${l}`));
};

const siteContent = read("site_content.json");
const home = siteContent.find((r) => r.section_key === "page_rows");
if (home) {
  const before = rowsOf(home.content);
  const restyled = restyleRows(before, { kind: "home" });
  check("home", before, restyled);
  homeRows = arrangeHome(applyGapContent(restyled, { kind: "home" }, gapNotes));
  home.content = withRows(home.content, homeRows);
  sql.push(`update public.site_content set draft_content = ${sqlJson(home.content)} where section_key = 'page_rows';`);
}

const pages = read("cms_pages.json");
for (const page of pages) {
  const slug = String(page.slug);
  const ctx = kindForSlug(slug);
  const before = rowsOf(page.page_rows);
  const restyled = restyleRows(before, ctx);
  check(slug, before, restyled);
  page.page_rows = withRows(page.page_rows, applyGapContent(restyled, { ...ctx, homeRows }, gapNotes));
  sql.push(`update public.cms_pages set draft_page_rows = ${sqlJson(page.page_rows)} where slug = '${slug.replace(/'/g, "''")}';`);
}
sql.push("commit;");

fs.writeFileSync(path.join(outDir, "site_content.json"), JSON.stringify(siteContent));
fs.writeFileSync(path.join(outDir, "cms_pages.json"), JSON.stringify(pages));
for (const extra of ["blog_posts.json", "work_items.json", "proof_points.json"]) {
  const src = path.join(snapshotDir, extra);
  if (fs.existsSync(src)) fs.copyFileSync(src, path.join(outDir, extra));
}
fs.writeFileSync(path.join(outDir, "text-diff.txt"), report.join("\n") + "\n");
const kindLabel = { reused: "Your own words, shown in one more place", label: "Button label", new: "New copy" } as const;
fs.writeFileSync(
  path.join(outDir, "gap-content.txt"),
  gapNotes.map((n) => `[${kindLabel[n.kind]}] ${n.where} (${n.field}): ${n.value}`).join("\n") + "\n",
);
console.log(report.join("\n"));
if (failed) {
  console.error("\nVisible text changed: no SQL written.");
  process.exit(1);
}
fs.writeFileSync(path.join(outDir, "restyle.sql"), sql.join("\n") + "\n");
console.log(`\nWrote ${path.join(outDir, "restyle.sql")}`);
